#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════════
//  ISS Weighbridge — renderer build
//
//  The app ships as ONE index.html (the hot-swap override in main.js loads a
//  single file, and a site PC has no dev server). Source lives as modules in
//  renderer/src; this script stitches them back together in manifest order.
//
//    node tools/build-renderer.mjs                 → renderer/index.html (brand: iss)
//    node tools/build-renderer.mjs --brand promnatic
//    node tools/build-renderer.mjs --out dist/x.html --no-banners
//
//  Modules are classic scripts concatenated into one <script>, so top-level
//  functions stay global and every inline onclick="…" keeps working.
//  Each module is framed by a banner comment, which lets tools/split-renderer
//  turn a built index.html back into modules if that is all you have.
// ════════════════════════════════════════════════════════════════════════════
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'renderer', 'src');

const args = process.argv.slice(2);
const opt = (name, dflt) => {
  const i = args.indexOf('--' + name);
  return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : dflt;
};
const flag = (name) => args.includes('--' + name);

const brandId = opt('brand', 'iss');
const out = path.resolve(ROOT, opt('out', path.join('renderer', 'index.html')));
const banners = !flag('no-banners');

const read = (rel) => fs.readFileSync(path.join(SRC, rel), 'utf8').replace(/\r\n/g, '\n');
const manifest = JSON.parse(read('manifest.json'));
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

// ── brand pack ──────────────────────────────────────────────────────────────
let brandJs = '';
let brandMeta = { appName: 'ISS Weighbridge' };
if (manifest.brands) {
  const dir = path.join(ROOT, 'renderer', 'brands', brandId);
  if (!fs.existsSync(dir)) { console.error(`✗ unknown brand "${brandId}" (no ${dir})`); process.exit(1); }
  brandMeta = JSON.parse(fs.readFileSync(path.join(dir, 'brand.json'), 'utf8'));
  // assets are named without an extension so a real logo can replace the
  // placeholder by just dropping in mark.png / lockup.png / ticket.png
  const asset = (base) => {
    for (const ext of ['png', 'svg', 'jpg', 'webp']) {
      const p = path.join(dir, `${base}.${ext}`);
      if (!fs.existsSync(p)) continue;
      const mime = ext === 'svg' ? 'image/svg+xml' : ext === 'jpg' ? 'image/jpeg' : 'image/' + ext;
      return `data:${mime};base64,` + fs.readFileSync(p).toString('base64');
    }
    return '';
  };
  const assets = brandMeta.assets || {};
  const resolved = Object.fromEntries(Object.entries(assets).filter(([k]) => k !== 'icon').map(([k, f]) => [k, asset(f)]));
  const { assets: _drop, ...rest } = brandMeta;
  brandJs = '// ── brand pack: ' + brandId + ' (generated by tools/build-renderer.mjs) ──\n'
    + 'const BRAND=Object.freeze(' + JSON.stringify({ id: brandId, ...rest, ...resolved }, null, 0) + ');\n'
    + 'window.BRAND=BRAND;\n';
}

// ── assemble ────────────────────────────────────────────────────────────────
const frame = (rel, text, kind) => banners
  ? `/*@module ${rel} */\n${text}${text.endsWith('\n') ? '' : '\n'}/*@end ${rel} */\n`
  : text;

let cssText = manifest.styles.map((f) => (banners ? `/*@module ${f} */\n` : '') + read(f)).join('');
// brand tokens land last so a pack can re-tint the surfaces and accents
if (brandMeta.tokens) {
  const t = brandMeta.tokens, map = { base: '--base', surface: '--surface', elev: '--elev', accent: '--accent', accentInk: '--accent-ink', gold: '--gold' };
  cssText += (banners ? '/*@module brand-tokens (generated) */\n' : '')
    + ':root{' + Object.entries(map).filter(([k]) => t[k]).map(([k, v]) => `${v}:${t[k]}`).join(';') + '}\n';
}
const vendorText = manifest.vendor.map((f) => read(f)).join('');
let appText = (brandJs ? frame('brand-pack (generated)', brandJs) : '')
  + manifest.app.map((f) => frame(f, read(f))).join('');

// build stamp: package.json is the single source of truth for the version
appText = appText.replace(/const RENDERER_BUILD='[^']*';/, () => `const RENDERER_BUILD='${pkg.version}';`);

// syntax gate — a renderer that does not parse is a black screen on site
for (const [label, code] of [['vendor', vendorText], ['app', appText]]) {
  try { new vm.Script(code, { filename: label + '.js' }); }
  catch (e) {
    // map the error line back to the module it came from
    const line = (e.stack.match(/:(\d+)\n/) || [])[1] | 0;
    let owner = '';
    if (line && banners) {
      const upTo = code.split('\n').slice(0, line).reverse().find((l) => l.startsWith('/*@module '));
      owner = upTo ? ' in ' + upTo.slice(10, -3) : '';
    }
    console.error(`✗ ${label} does not parse${owner}: ${e.message}`);
    process.exit(1);
  }
}

// placeholders are filled in the TEMPLATE only, before any code is injected —
// the app itself is never scanned for {{…}}
const tpl = read('index.template.html')
  .replace(/\{\{THEME_COLOR\}\}/g, () => (brandMeta.tokens && brandMeta.tokens.base) || '#0A1120')
  .replace(/\{\{([a-zA-Z]+)\}\}/g, (m, k) => {
    const v = brandMeta[k];
    return typeof v === 'string' ? v.replace(/&/g, '&amp;').replace(/</g, '&lt;') : m;
  });
const html = tpl
  // function replacers: a string replacement would expand "$'" / "$&" inside
  // the code itself (the QR library has case '$' — that broke the first build)
  .replace('<!--@styles-->\n', () => cssText)
  .replace('<!--@vendor-->', () => vendorText)
  .replace('<!--@app-->', () => appText);

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, html, 'utf8');
const kb = (Buffer.byteLength(html) / 1024).toFixed(0);
console.log(`✓ renderer ${pkg.version} · brand ${brandId} · ${manifest.app.length} modules · ${kb} kB → ${path.relative(ROOT, out)}`);
